import { contextBridge, ipcRenderer } from 'electron';
import type { DesktopAPI } from '../../../packages/contracts';
const api: DesktopAPI = {
  googleStatus: () => ipcRenderer.invoke('google:status'),
  googleAction: action => ipcRenderer.invoke('google:action', action),
  chat: input => ipcRenderer.invoke('workspace:chat', input),
  attachPDF: projectId => ipcRenderer.invoke('workspace:attach-pdf', { projectId }),
  removePDF: input => ipcRenderer.invoke('workspace:remove-pdf', input),
  importBrief: () => ipcRenderer.invoke('workspace:import-brief'),
  onGoogle: listener => { const handler = (_event: Electron.IpcRendererEvent, value: Parameters<typeof listener>[0]) => listener(value); ipcRenderer.on('google:status', handler); return () => ipcRenderer.removeListener('google:status', handler); },
  load: () => ipcRenderer.invoke('workspace:load'),
  command: command => ipcRenderer.invoke('workspace:command', command),
  plan: input => ipcRenderer.invoke('workspace:plan', input),
  draft: input => ipcRenderer.invoke('workspace:draft', input),
  flush: () => ipcRenderer.invoke('workspace:flush'),
  openResource: id => ipcRenderer.invoke('workspace:open-resource', id),
  browserStatus: () => ipcRenderer.invoke('browser:status'),
  pairing: reset => ipcRenderer.invoke('browser:pairing', reset),
  copyPairingToken: () => ipcRenderer.invoke('browser:copy-pairing-token'),
  restoreTab: () => ipcRenderer.invoke('browser:restore'),
  nudgeStatus: () => ipcRenderer.invoke('nudge:status'),
  showWorkspace: () => ipcRenderer.invoke('ui:show'),
  respondToNudge: action => ipcRenderer.invoke('nudge:respond', action),
  demoDetour: () => ipcRenderer.invoke('nudge:demo'),
  previewVoice: () => ipcRenderer.invoke('nudge:preview'),
  speechReady: () => ipcRenderer.invoke('speech:ready'),
  setNudgeRegions: regions => ipcRenderer.send('nudge:regions', regions),
  onNudge: listener => { const handler = (_event: Electron.IpcRendererEvent, value: Parameters<typeof listener>[0]) => listener(value); ipcRenderer.on('nudge:status', handler); return () => ipcRenderer.removeListener('nudge:status', handler); },
  onSpeech: listener => { const handler = (_event: Electron.IpcRendererEvent, value: Parameters<typeof listener>[0]) => listener(value); ipcRenderer.on('speech:event', handler); return () => ipcRenderer.removeListener('speech:event', handler); },
  onNavigate: listener => { const handler = (_event: Electron.IpcRendererEvent, view: 'work' | 'return') => listener(view); ipcRenderer.on('ui:navigate', handler); return () => ipcRenderer.removeListener('ui:navigate', handler); },
  onBrowser: listener => { const handler = (_event: Electron.IpcRendererEvent, status: Parameters<typeof listener>[0]) => listener(status); ipcRenderer.on('browser:status', handler); return () => ipcRenderer.removeListener('browser:status', handler); },
  onSaveError: listener => { ipcRenderer.on('workspace:save-error', listener); return () => ipcRenderer.removeListener('workspace:save-error', listener); },
  onState: listener => { const handler = (_event: Electron.IpcRendererEvent, state: Parameters<typeof listener>[0]) => listener(state); ipcRenderer.on('workspace:state', handler); return () => ipcRenderer.removeListener('workspace:state', handler); },
};
contextBridge.exposeInMainWorld('dopamigo', api);
