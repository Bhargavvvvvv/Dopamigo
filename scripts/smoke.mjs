import { _electron } from 'playwright';
import electron from 'electron';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
const data = await fs.mkdtemp(path.join(os.tmpdir(), 'dopamigo-e2e-'));
await fs.mkdir('test-results', { recursive: true });
const env = { ...process.env, DOPAMIGO_DATA_DIR: data, DOPAMIGO_PORT: '0' };
delete env.ELECTRON_RUN_AS_NODE; delete env.DOPAMIGO_DEV_URL;
let app;
async function launch() { app = await _electron.launch({ executablePath: electron, args: ['.'], env }); const page = await app.firstWindow(); await page.getByRole('heading', { name: 'Dopamigo', exact: true }).waitFor(); return page; }
try {
  let page = await launch();
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  assert.equal(await page.evaluate(() => typeof window.require), 'undefined');
  await page.getByRole('button', { name: /Settings/ }).click();
  await page.getByRole('checkbox', { name: /Reduce motion/ }).click();
  await page.waitForFunction(() => document.querySelector('input[type=checkbox]')?.checked === true);
  await page.getByRole('button', { name: /Plan/ }).click();
  await page.getByLabel(/Task name|What’s on your mind/).fill('Literature review on urban green spaces');
  await page.getByLabel(/Assignment brief/).fill('Compare three studies. Draft a 1500-word review and identify one research gap.');
  await page.getByRole('button', { name: /Create plan|Make a small plan/ }).click();
  await page.getByText(/DEV MOCK PLAN|Development mock plan|Sample plan/, { exact: true }).waitFor();
  await page.getByRole('button', { name: /Make it smaller/ }).click();
  await page.getByRole('heading', { name: /Write one rough bullet:/ }).waitFor();
  await page.screenshot({ path: 'test-results/plan.png' });
  await page.getByRole('button', { name: /Open workspace|Go to work/ }).click();
  await page.getByRole('button', { name: 'Start session', exact: true }).click();
  await page.getByText('In session', { exact: true }).waitFor();
  await page.getByLabel('Work notes').fill('Study A includes 240 students. Compare its methods with Study B.');
  await page.getByRole('button', { name: /^Return/ }).click();
  await page.getByRole('button', { name: /^Work/ }).click();
  assert.equal(await page.getByLabel('Work notes').inputValue(), 'Study A includes 240 students. Compare its methods with Study B.');
  await page.getByLabel('My exact next action').fill('Compare the sample sizes in Study A and Study B.');
  await page.getByLabel('Link name').fill('Source notes');
  await page.getByLabel('Resource URL').fill('https://example.org/review');
  await page.getByRole('button', { name: 'Save link', exact: true }).click();
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await page.getByText('Paused', { exact: true }).waitFor();
  await page.screenshot({ path: 'test-results/work.png' });
  assert.deepEqual(errors, []);
  await app.evaluate(({ app }) => app.quit()).catch(() => {}); await app.close(); app = undefined;
  page = await launch();
  await page.getByRole('heading', { name: 'Where you left off' }).waitFor();
  await page.getByText('Study A includes 240 students. Compare its methods with Study B.', { exact: true }).waitFor();
  // Intercept only the OS browser launch; verify the exact saved URL reaches Electron.
  await app.evaluate(({ shell }) => { globalThis.openedResource = null; shell.openExternal = async url => { globalThis.openedResource = url; }; });
  await page.screenshot({ path: 'test-results/return.png' });
  await page.getByRole('button', { name: 'Continue working' }).click();
  await page.getByText('In session', { exact: true }).waitFor();
  assert.equal(await app.evaluate(() => globalThis.openedResource), 'https://example.org/review');
  assert.equal(await page.getByLabel('Work notes').inputValue(), 'Study A includes 240 students. Compare its methods with Study B.');
  assert.equal(await page.getByLabel('My exact next action').inputValue(), 'Compare the sample sizes in Study A and Study B.');
  await page.getByRole('button', { name: /Settings/ }).click();
  await page.getByRole('checkbox', { name: /Mute spoken nudges/ }).click();
  await page.waitForFunction(async () => (await window.dopamigo.load()).value.state.preferences.muted);
  await page.getByRole('checkbox', { name: /Enable browser monitoring/ }).click();
  await page.waitForFunction(async () => (await window.dopamigo.load()).value.state.preferences.monitoring);
  await page.getByRole('checkbox', { name: /^Demo timing/ }).click();
  await page.getByRole('button', { name: 'Demo: simulate a browser detour' }).click();
  await page.getByRole('region', { name: 'Dopamigo nudge' }).waitFor();
  await page.screenshot({ path: 'test-results/nudge.png' });
  await page.getByRole('button', { name: 'This is research', exact: true }).click();
  await page.getByRole('region', { name: 'Dopamigo nudge' }).waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: /Work/ }).click();
  await page.getByRole('button', { name: 'Take a break', exact: true }).click();
  await page.getByText('On a break', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'End session', exact: true }).click();
  await page.getByRole('button', { name: /Plan/ }).click();
  await page.getByRole('heading', { name: 'Literature review on urban green spaces', exact: true }).waitFor();
  await page.getByRole('button', { name: /Settings/ }).click();
  assert.equal(await page.getByRole('checkbox', { name: /Reduce motion/ }).isChecked(), true);
  console.log('PASS: actual Electron task → plan → smaller step → start → notes/resources → pause → restart → resume → break → end.');
} finally { if (app) { await app.evaluate(({ app }) => app.quit()).catch(() => {}); await app.close(); } }
